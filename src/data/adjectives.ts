export interface AdjectiveItem {
  id: number;
  level: "N5" | "N4" | "N3" | "N2" | "N1";
  adjective: string;
  romaji: string;
  meaning: string;
  type: "い-Adjective" | "な-Adjective";
  negative: string;
  past: string;
  pastNegative: string;
}

type BaseAdjective = {
  id: number;
  level: AdjectiveItem["level"];
  adjective: string;
  romaji: string;
  meaning: string;
  type: AdjectiveItem["type"];
};

function makeI(item: Omit<BaseAdjective, "type">): AdjectiveItem {
  const word = item.adjective;

  // Special adjective: いい
  if (word === "いい") {
    return {
      ...item,
      type: "い-Adjective",
      negative: "Yokunai",
      past: "Yokatta",
      pastNegative: "Yokunakatta",
    };
  }

  return {
    ...item,
    type: "い-Adjective",
    negative: `${item.romaji.slice(0, -1)}kunai`,
    past: `${item.romaji.slice(0, -1)}katta`,
    pastNegative: `${item.romaji.slice(0, -1)}kunakatta`,
  };
}

function makeNa(item: Omit<BaseAdjective, "type">): AdjectiveItem {
  return {
    ...item,
    type: "な-Adjective",
    negative: `${item.romaji} janai`,
    past: `${item.romaji} datta`,
    pastNegative: `${item.romaji} janakatta`,
  };
}

