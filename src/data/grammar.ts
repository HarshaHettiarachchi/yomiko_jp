export function getGrammarByLevel(
  level: GrammarItem["level"],
): GrammarItem[] {
  return grammarData.filter((item) => item.level === level);
}

export function getGrammarById(id: number): GrammarItem | undefined {
  return grammarData.find((item) => item.id === id);
}